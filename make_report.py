W,H=A4; CW=W-40*mm; story=[]
def para(txt, kind='body'): story.append(Paragraph(txt,style[kind]))
def title(txt): para(txt,'h')
def sub(txt): para(txt,'h2')
def bullet(txt):para('• '+txt,'bullet')
def gap(x=8):story.append(Spacer(1,x))
def page():story.append(PageBreak())
def table(rows,widths=None):
    rows=[[Paragraph(str(v),style['th' if i==0 else 'td']) for v in row] for i,row in enumerate(rows)]
    tb=Table(rows,colWidths=widths,repeatRows=1,hAlign='LEFT')
    tb.setStyle(TableStyle([('BACKGROUND',(0,0),(-1,0),NAVY),('ROWBACKGROUNDS',(0,1),(-1,-1),[colors.white,ALT]),
            ('VALIGN',(0,0),(-1,-1),'TOP'),('LEFTPADDING',(0,0),(-1,-1),7),('RIGHTPADDING',(0,0),(-1,-1),7),
            ('TOPPADDING',(0,0),(-1,-1),6),('BOTTOMPADDING',(0,0),(-1,-1),6),('LINEBELOW',(0,1),(-1,-1),.2,LINE)]))
    story.append(tb);gap(7)
def figure(filename,max_height=None):
    path=ROOT/'figures'/filename
    with PILImage.open(path) as im: w,h=im.size
    width=CW
    if max_height and width*h/w > max_height: width=max_height*w/h
    story.append(Image(str(path),width=width,height=width*h/w,hAlign='CENTER'))
def event_table(name,n=5):
    items=DATA[name]['largest_events'][:n]
    lines=[['Диапазон X','Время, начало — конец','Пик ΔY','Замеров']]
    for e in items:
        lines.append([f"{e['x_start']}–{e['x_end']}",f"{e['first_seen'][11:16]}–{e['last_seen'][11:16]}",f"{e['peak_delta_y']:+.2f}",str(e['frames'])])
    table(lines,[120,155,116,105])
def footer(canvas,doc):
    canvas.saveState()
    canvas.setFillColor(NAVY);canvas.rect(0,H-12,W,12,stroke=0,fill=1)
    canvas.setFont('DVR',7.2);canvas.setFillColor(SUB)
    canvas.drawString(20*mm,15*mm,'FIBERSENSE | АНАЛИЗ ДАННЫХ | ХАКАТОН')
    canvas.drawRightString(W-20*mm,15*mm,str(doc.page))
    canvas.restoreState()

